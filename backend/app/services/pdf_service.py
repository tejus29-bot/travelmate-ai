# ---------------------------------------------------------------------------
# Page background callback
# ---------------------------------------------------------------------------

def _header_canvas(canvas, doc):
    """Draw a coloured header strip on every page."""
    canvas.saveState()
    # Top strip
    canvas.setFillColor(PRIMARY)
    canvas.rect(0, A4[1] - 18 * mm, A4[0], 18 * mm, fill=True, stroke=False)
    # Footer line
    canvas.setFillColor(SECONDARY)
    canvas.rect(0, 0, A4[0], 8 * mm, fill=True, stroke=False)
    canvas.setFont("Helvetica", 7)
    canvas.setFillColor(WHITE)
    canvas.drawCentredString(A4[0] / 2, 3 * mm, "Generated by TravelMate AI  •  travelmate.ai")
    canvas.restoreState()



def generate_itinerary_pdf(itinerary_data: dict, trip_data: dict) -> bytes:
    """
    Generate a styled PDF for the given itinerary and trip metadata.

    Args:
        itinerary_data: The full ItineraryData dict (as returned by ai_service).
        trip_data:      The Trip dict stored in Supabase (or the original request dict).

    Returns:
        Raw PDF bytes suitable for streaming or saving.
    """
    buffer = io.BytesIO()

    doc = SimpleDocTemplate(
        buffer,
        pagesize=A4,
        rightMargin=2 * cm,
        leftMargin=2 * cm,
        topMargin=2.5 * cm,
        bottomMargin=2 * cm,
        title=itinerary_data.get("trip_title", "Travel Itinerary"),
        author="TravelMate AI",
        subject=f"Itinerary for {itinerary_data.get('destination', '')}",
    )

    styles = _styles()
    story: list = []

    # Title page
    story.extend(_title_section(itinerary_data, trip_data, styles))

    # Budget overview
    story.extend(_budget_section(itinerary_data, styles))

    # Day-by-day itinerary
    story.extend(_itinerary_section(itinerary_data, styles))

    # Travel tips
    story.extend(_tips_section(itinerary_data, styles))

    # Generation timestamp
    ts = datetime.utcnow().strftime("%Y-%m-%d %H:%M UTC")
    story.append(Paragraph(f"Generated on {ts} by TravelMate AI", styles["small"]))

    doc.build(story, onFirstPage=_header_canvas, onLaterPages=_header_canvas)

    return buffer.getvalue()

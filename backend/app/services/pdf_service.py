def _title_section(itinerary: dict, trip: dict, styles: dict) -> list:
    elements: list = []

    trip_title = itinerary.get("trip_title", "Travel Itinerary")
    destination = itinerary.get("destination", trip.get("destination", ""))
    start_date = trip.get("start_date", itinerary.get("start_date", ""))
    end_date = trip.get("end_date", itinerary.get("end_date", ""))
    travelers = trip.get("travelers", 1)
    travel_style = trip.get("travel_style", "moderate").capitalize()

    # Blue background title block — simulated via a single-cell Table
    header_data = [
        [Paragraph(trip_title, styles["title"])],
        [Paragraph(destination, styles["subtitle"])],
        [Paragraph(f"{start_date}  →  {end_date}  •  {travelers} Traveller(s)  •  {travel_style}", styles["subtitle"])],
    ]
    header_table = Table(header_data, colWidths=[16 * cm])
    header_table.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, -1), PRIMARY),
        ("ALIGN", (0, 0), (-1, -1), "CENTER"),
        ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
        ("TOPPADDING", (0, 0), (-1, -1), 14),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 14),
        ("LEFTPADDING", (0, 0), (-1, -1), 20),
        ("RIGHTPADDING", (0, 0), (-1, -1), 20),
        ("ROUNDEDCORNERS", (0, 0), (-1, -1), [6, 6, 6, 6]),
    ]))
    elements.append(Spacer(1, 6 * mm))
    elements.append(header_table)
    elements.append(Spacer(1, 6 * mm))

    # Summary
    summary = itinerary.get("summary", "")
    if summary:
        elements.append(Paragraph(summary, styles["body"]))
        elements.append(Spacer(1, 4 * mm))

    return elements


def _budget_section(itinerary: dict, styles: dict) -> list:
    elements: list = []

    breakdown = itinerary.get("budget_breakdown", {})
    total = itinerary.get("total_estimated_budget", 0)
    currency = itinerary.get("currency", "USD")

    # Section header
    hdr_table = Table([[Paragraph("💰  Budget Overview", styles["section_header"])]], colWidths=[16 * cm])
    hdr_table.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, -1), SECONDARY),
        ("LEFTPADDING", (0, 0), (-1, -1), 12),
        ("TOPPADDING", (0, 0), (-1, -1), 8),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 8),
        ("ROUNDEDCORNERS", (0, 0), (-1, -1), [4, 4, 4, 4]),
    ]))
    elements.append(hdr_table)
    elements.append(Spacer(1, 3 * mm))

    # Budget table
    category_labels = {
        "accommodation": "🏨 Accommodation",
        "food": "🍽️ Food & Dining",
        "transportation": "🚗 Transportation",
        "activities": "🎯 Activities",
        "miscellaneous": "🛍️ Miscellaneous",
    }
    rows = [["Category", f"Amount ({currency})", "% of Budget"]]
    for key, label in category_labels.items():
        val = breakdown.get(key, 0)
        pct = f"{(val / total * 100):.1f}%" if total > 0 else "0%"
        rows.append([label, f"{val:,.2f}", pct])
    rows.append(["TOTAL", f"{total:,.2f}", "100%"])

    budget_table = Table(rows, colWidths=[8 * cm, 4 * cm, 4 * cm])
    budget_table.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, 0), PRIMARY),
        ("TEXTCOLOR", (0, 0), (-1, 0), WHITE),
        ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
        ("FONTSIZE", (0, 0), (-1, 0), 10),
        ("ALIGN", (1, 0), (-1, -1), "RIGHT"),
        ("ALIGN", (0, 0), (0, -1), "LEFT"),
        ("FONTNAME", (0, 1), (-1, -2), "Helvetica"),
        ("FONTSIZE", (0, 1), (-1, -2), 9),
        ("ROWBACKGROUNDS", (0, 1), (-1, -2), [WHITE, LIGHT_BG]),
        ("BACKGROUND", (0, -1), (-1, -1), ACCENT),
        ("FONTNAME", (0, -1), (-1, -1), "Helvetica-Bold"),
        ("TEXTCOLOR", (0, -1), (-1, -1), DARK_TEXT),
        ("GRID", (0, 0), (-1, -1), 0.4, colors.HexColor("#CBD5E1")),
        ("TOPPADDING", (0, 0), (-1, -1), 5),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 5),
        ("LEFTPADDING", (0, 0), (-1, -1), 8),
        ("RIGHTPADDING", (0, 0), (-1, -1), 8),
    ]))
    elements.append(budget_table)
    elements.append(Spacer(1, 6 * mm))
    return elements


def _itinerary_section(itinerary: dict, styles: dict) -> list:
    elements: list = []

    # Section header
    hdr_table = Table([[Paragraph("📅  Day-by-Day Itinerary", styles["section_header"])]], colWidths=[16 * cm])
    hdr_table.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, -1), SECONDARY),
        ("LEFTPADDING", (0, 0), (-1, -1), 12),
        ("TOPPADDING", (0, 0), (-1, -1), 8),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 8),
        ("ROUNDEDCORNERS", (0, 0), (-1, -1), [4, 4, 4, 4]),
    ]))
    elements.append(hdr_table)
    elements.append(Spacer(1, 3 * mm))

    category_icons = {
        "sightseeing": "👁",
        "food": "🍽",
        "transport": "🚗",
        "transportation": "🚗",
        "museum": "🏛",
        "culture": "🎭",
        "outdoor": "🌲",
        "adventure": "🧗",
        "entertainment": "🎵",
        "leisure": "☕",
        "shopping": "🛍",
    }

    for day in itinerary.get("days", []):
        day_num = day.get("day_number", "?")
        day_date = day.get("date", "")
        theme = day.get("theme", "")

        elements.append(
            Paragraph(f"Day {day_num}  —  {day_date}  |  {theme}", styles["day_header"])
        )
        elements.append(HRFlowable(width="100%", thickness=1, color=SECONDARY, spaceAfter=4))

        for act in day.get("activities", []):
            name = act.get("name", "Activity")
            desc = act.get("description", "")
            location = act.get("location", "")
            start = act.get("start_time", "")
            end = act.get("end_time", "")
            cost = act.get("estimated_cost", 0)
            category = act.get("category", "").lower()
            travel_time = act.get("travel_time_from_previous", "")
            booking = act.get("booking_required", False)
            currency = itinerary.get("currency", "USD")

            icon = category_icons.get(category, "📍")
            booking_note = " 🎟 Booking required" if booking else ""
            travel_note = f" | 🚶 {travel_time}" if travel_time and travel_time != "N/A" else ""

            elements.append(
                Paragraph(f"{icon} {name}  ({start} – {end})", styles["activity_name"])
            )
            if desc:
                elements.append(Paragraph(desc, styles["activity_body"]))
            elements.append(
                Paragraph(
                    f"📍 {location}  |  💵 {currency} {cost:,.2f}{travel_note}{booking_note}",
                    styles["activity_body"],
                )
            )
            elements.append(Spacer(1, 2 * mm))

        elements.append(Spacer(1, 4 * mm))

    return elements


def _tips_section(itinerary: dict, styles: dict) -> list:
    elements: list = []

    tips = itinerary.get("travel_tips", [])
    if not tips:
        return elements

    hdr_table = Table([[Paragraph("💡  Travel Tips", styles["section_header"])]], colWidths=[16 * cm])
    hdr_table.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, -1), SUCCESS),
        ("LEFTPADDING", (0, 0), (-1, -1), 12),
        ("TOPPADDING", (0, 0), (-1, -1), 8),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 8),
        ("ROUNDEDCORNERS", (0, 0), (-1, -1), [4, 4, 4, 4]),
    ]))
    elements.append(hdr_table)
    elements.append(Spacer(1, 3 * mm))

    for i, tip in enumerate(tips, start=1):
        elements.append(Paragraph(f"{i}.  {tip}", styles["tip"]))

    elements.append(Spacer(1, 6 * mm))
    return elements


